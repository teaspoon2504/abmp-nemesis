#!/usr/bin/env node
/**
 * SQLite to MySQL Export Script
 * Exports database to MySQL-compatible SQL format with batched inserts
 */

import Database from 'better-sqlite3';
import fs from 'node:fs';
import path from 'node:path';

const DB_PATH = process.argv[2] || './data/dashboard.sqlite';
const OUTPUT_DIR = process.argv[3] || './mysql-export';
const BATCH_SIZE = parseInt(process.argv[4]) || 10000;

console.log('📦 SQLite to MySQL Export Tool');
console.log('=============================');
console.log(`Source: ${DB_PATH}`);
console.log(`Output: ${OUTPUT_DIR}`);
console.log(`Batch size: ${BATCH_SIZE}`);
console.log('');

// Create output directory
if (!fs.existsSync(OUTPUT_DIR)) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
}

// Open database
const db = new Database(DB_PATH, { readonly: true });

// Helper: convert SQLite types to MySQL types
function sqliteTypeToMySQL(col) {
  const decl = col.dflt_value;
  const type = col.type?.toUpperCase() || '';

  if (type.includes('INT')) return 'INT';
  if (type.includes('REAL') || type.includes('FLOAT') || type.includes('DOUBLE')) return 'DOUBLE';
  return 'VARCHAR(255)';
}

// Helper: escape value for MySQL
function escapeMySQL(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  const str = String(value);
  // Escape single quotes and backslashes
  return `'${str.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

// 1. Export Schema
console.log('📝 Step 1: Exporting schema...');
let schemaSQL = '-- MySQL Schema for Nemesis Dashboard\n';
schemaSQL += '-- Generated by SQLite to MySQL Export Tool\n\n';
schemaSQL += 'SET NAMES utf8mb4;\n';
schemaSQL += 'SET FOREIGN_KEY_CHECKS = 0;\n\n';

// Get table info
const tables = ['assets', 'regions', 'provinces', 'packages', 'package_regions', 'package_provinces',
                'region_metrics', 'province_metrics', 'owner_metrics'];

for (const table of tables) {
  const columns = db.prepare(`PRAGMA table_info(${table})`).all();

  schemaSQL += `-- Table: ${table}\n`;
  schemaSQL += `DROP TABLE IF EXISTS ${table};\n`;
  schemaSQL += `CREATE TABLE ${table} (\n`;

  const colDefs = columns.map(col => {
    const type = col.type?.toUpperCase() || 'TEXT';
    let mysqlType = 'TEXT';

    if (type.includes('INTEGER')) mysqlType = 'INT';
    else if (type.includes('REAL')) mysqlType = 'DOUBLE';
    else if (type.includes('BLOB')) mysqlType = 'LONGTEXT';
    else mysqlType = 'TEXT';

    return `  ${col.name} ${mysqlType}${col.notnull ? ' NOT NULL' : ''}${col.pk ? ' PRIMARY KEY' : ''}`;
  });

  schemaSQL += colDefs.join(',\n');
  schemaSQL += '\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;\n\n';
}

fs.writeFileSync(path.join(OUTPUT_DIR, '001-schema.sql'), schemaSQL);
console.log('✅ Schema exported to 001-schema.sql');

// 2. Export Data
console.log('\n📊 Step 2: Exporting data...');

const tableRowCounts = {};
for (const table of tables) {
  const count = db.prepare(`SELECT COUNT(*) as cnt FROM ${table}`).get().cnt;
  tableRowCounts[table] = count;
  console.log(`  ${table}: ${count.toLocaleString()} rows`);
}

let fileNum = 2;
let totalBytes = 0;

for (const table of tables) {
  const count = tableRowCounts[table];
  if (count === 0) continue;

  console.log(`\n  Exporting ${table}...`);

  // Get columns
  const columns = db.prepare(`PRAGMA table_info(${table})`).all().map(c => c.name);
  const colList = columns.join(', ');

  // Export in batches
  let offset = 0;
  let batchNum = 0;
  let tableFileNum = fileNum;

  while (offset < count) {
    const rows = db.prepare(`SELECT * FROM ${table} LIMIT ${BATCH_SIZE} OFFSET ${offset}`).all();

    if (rows.length === 0) break;

    let batchSQL = '';
    for (const row of rows) {
      const values = columns.map(col => {
        const val = row[col];
        return escapeMySQL(val);
      });
      batchSQL += `INSERT INTO ${table} (${colList}) VALUES (${values.join(', ')});\n`;
    }

    const filename = `${String(tableFileNum).padStart(3, '0')}-${table}-batch-${batchNum}.sql`;
    fs.writeFileSync(path.join(OUTPUT_DIR, filename), batchSQL);

    totalBytes += Buffer.byteLength(batchSQL, 'utf8');
    offset += BATCH_SIZE;
    batchNum++;
    fileNum++;

    const progress = Math.min(100, Math.round((offset / count) * 100));
    process.stdout.write(`\r    Progress: ${progress}% (${offset.toLocaleString()}/${count.toLocaleString()})`);
  }
  console.log('');
}

console.log('\n=============================');
console.log('✅ Export complete!');
console.log(`📁 Files: ${fileNum - 1}`);
console.log(`💾 Total data: ${(totalBytes / 1024 / 1024).toFixed(2)} MB`);
console.log('');
console.log('📋 Next steps:');
console.log('1. Upload files to shared hosting via SSH/cPanel');
console.log('2. Import 001-schema.sql first (creates tables)');
console.log('3. Import data files in numerical order');
console.log('4. Or use: mysql -u user -p database < 001-schema.sql');
console.log('5. Then: cat *.sql | mysql -u user -p database');

db.close();